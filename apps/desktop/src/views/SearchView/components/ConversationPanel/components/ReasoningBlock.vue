<script setup lang="ts">
    import AppIcon from '@components/AppIcon.vue';
    import MarkdownContent from '@components/MarkdownContent.vue';
    import { computed, nextTick, onMounted, onUnmounted, ref, useId, watch } from 'vue';

    import { t } from '@/i18n';

    const props = defineProps<{
        content: string;
        isStreaming: boolean;
        startedAt?: number;
        endedAt?: number;
        durationMs?: number;
    }>();

    const contentId = useId();
    const preview = computed(() => props.content.replace(/\s+/g, ' ').trim());
    const reasoningContentRef = ref<HTMLElement | null>(null);
    const isExpanded = ref(props.isStreaming);
    const now = ref(Date.now());
    const fallbackStartedAt = ref(props.startedAt ?? now.value);
    const shouldFollowContent = ref(true);
    let elapsedTimer: ReturnType<typeof setInterval> | null = null;
    let isSyncingScroll = false;

    const hasWallClockDuration = computed(
        () => props.startedAt !== undefined && props.endedAt !== undefined
    );
    const hasDuration = computed(
        () => hasWallClockDuration.value || props.durationMs !== undefined
    );
    const elapsedMs = computed(() => {
        if (props.isStreaming) {
            return Math.max(0, now.value - (props.startedAt ?? fallbackStartedAt.value));
        }
        if (hasWallClockDuration.value) {
            return Math.max(0, props.endedAt! - props.startedAt!);
        }
        return Math.max(0, props.durationMs ?? 0);
    });
    const elapsedSeconds = computed(() => Math.max(1, Math.floor(elapsedMs.value / 1000)));
    const label = computed(() => {
        if (props.isStreaming) {
            return t('assistant.reasoning.thinking', {
                seconds: elapsedSeconds.value,
            });
        }

        if (hasDuration.value) {
            return t('assistant.reasoning.completed', {
                seconds: elapsedSeconds.value,
            });
        }

        return t('assistant.reasoning.completedWithoutTiming');
    });

    function stopElapsedTimer() {
        if (elapsedTimer !== null) {
            clearInterval(elapsedTimer);
            elapsedTimer = null;
        }
    }

    function updateElapsed() {
        now.value = Date.now();
    }

    function startElapsedTimer() {
        stopElapsedTimer();
        updateElapsed();
        if (props.isStreaming) {
            elapsedTimer = setInterval(updateElapsed, 1000);
        }
    }

    function isScrolledToBottom(element: HTMLElement): boolean {
        return element.scrollHeight - element.scrollTop - element.clientHeight <= 8;
    }

    function syncContentToBottom() {
        const element = reasoningContentRef.value;
        if (!element || !shouldFollowContent.value) {
            return;
        }

        const maxScrollTop = Math.max(0, element.scrollHeight - element.clientHeight);
        if (element.scrollTop === maxScrollTop) {
            return;
        }

        isSyncingScroll = true;
        element.scrollTop = maxScrollTop;
        if (typeof window !== 'undefined' && 'requestAnimationFrame' in window) {
            window.requestAnimationFrame(() => {
                isSyncingScroll = false;
            });
        } else {
            isSyncingScroll = false;
        }
    }

    function handleContentScroll() {
        const element = reasoningContentRef.value;
        if (!element || !isExpanded.value) {
            return;
        }

        // Ignore the scroll event generated by our own jump to the bottom, but
        // still treat an upward user scroll in the same frame as manual input.
        if (isSyncingScroll && isScrolledToBottom(element)) {
            isSyncingScroll = false;
            return;
        }

        isSyncingScroll = false;
        shouldFollowContent.value = isScrolledToBottom(element);
    }

    async function syncExpandedContent() {
        await nextTick();
        if (isExpanded.value) {
            syncContentToBottom();
        }
    }

    function toggleExpanded() {
        isExpanded.value = !isExpanded.value;
        if (isExpanded.value) {
            void syncExpandedContent();
        }
    }

    // 每轮思考独立折叠；流式期间默认展开，但仍允许用户手动收起。
    watch(
        () => [props.isStreaming, props.startedAt, props.endedAt, props.durationMs] as const,
        ([streaming, startedAt]) => {
            if (startedAt !== undefined) {
                fallbackStartedAt.value = startedAt;
            }
            isExpanded.value = streaming;
            startElapsedTimer();
            void syncExpandedContent();
        },
        { immediate: true }
    );

    // 思考内容持续增长时，如果用户之前就在底部，则继续跟随最新内容；
    // 用户主动向上翻阅时保留阅读位置，直到再次滚到底部。
    watch(
        () => props.content,
        () => {
            void syncExpandedContent();
        }
    );

    onMounted(() => {
        void syncExpandedContent();
    });

    onUnmounted(() => {
        stopElapsedTimer();
    });
</script>

<template>
    <div class="reasoning-section w-full">
        <button
            type="button"
            class="reasoning-trigger"
            :class="{ 'reasoning-trigger-preview': !isExpanded && preview }"
            :aria-expanded="isExpanded"
            :aria-controls="contentId"
            @click="toggleExpanded"
        >
            <span class="reasoning-heading" role="status">
                <span class="reasoning-label">
                    <span
                        class="reasoning-label-content"
                        :class="{ 'reasoning-shimmer': isStreaming }"
                    >
                        {{ label }}
                    </span>
                </span>
                <AppIcon
                    :name="isExpanded ? 'chevron-down' : 'chevron-right'"
                    class="reasoning-disclosure-icon shrink-0"
                    aria-hidden="true"
                />
            </span>
            <template v-if="!isExpanded && preview">
                <span class="reasoning-preview-separator" aria-hidden="true">·</span>
                <span class="reasoning-preview" data-no-i18n="true" translate="no">
                    {{ preview }}
                </span>
            </template>
        </button>

        <div
            :id="contentId"
            class="reasoning-trace"
            :class="{ 'reasoning-trace-expanded': isExpanded }"
            :aria-hidden="!isExpanded"
        >
            <div class="reasoning-trace-clip">
                <div class="reasoning-trace-inner">
                    <span class="reasoning-trace-line" aria-hidden="true"></span>
                    <div
                        ref="reasoningContentRef"
                        class="reasoning-content custom-scrollbar-thin"
                        @scroll="handleContentScroll"
                    >
                        <MarkdownContent
                            :content="content"
                            :final="!isStreaming"
                            variant="reasoning"
                        />
                    </div>
                </div>
            </div>
        </div>
    </div>
</template>

